void get_headers_helper(IMpoHttp *h)
{
	StreamMsg msg = MSG_ERROR;

	// process all the headers
	do
	{
		msg = h->GetHeaders(100);
	} while (msg == MSG_TIMEOUT);

	TEST_REQUIRE(msg == MSG_OK);
}

void test_chunked_helper(IMpoHttp *h)
{
	get_headers_helper(h);

	// we expect result to succeed, but the length to be 0
	TEST_REQUIRE (h->GetContentLength() == 0);

	string buf = "";

	bool bFillBufResult = (h->FillBuf(buf, 5000) == MSG_END);
	TEST_REQUIRE(bFillBufResult);

	bool bMD5Matches = (mpom::str_case_eq(mpom::compute_md5((const unsigned char *) buf.data(), (unsigned int) buf.size()),
		"9d0b4cc377c401d500d97122cdbdb95a"));

	TEST_CHECK(bMD5Matches);

}

